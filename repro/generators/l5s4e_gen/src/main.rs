// Emits the depth-1 node data of the real certificate (t1.bin + wp0a::child) as a Lean module.
use wp0a::*;
fn rdu32(b: &[u8], p: &mut usize) -> u32 { let x = u32::from_le_bytes(b[*p..*p + 4].try_into().unwrap()); *p += 4; x }
fn rdi32(b: &[u8], p: &mut usize) -> i128 { rdu32(b, p) as i32 as i128 }
fn v5s(v: &V5) -> String { format!("![{}, {}, {}, {}, {}]", v[0], v[1], v[2], v[3], v[4]) }
fn wmin(x: &V5, w: i128) -> i128 { x.iter().map(|&a| { let r = a.rem_euclid(w); r.min(w - r) }).min().unwrap() }
fn main() {
    let args: Vec<String> = std::env::args().collect();
    let b = std::fs::read(&args[1]).unwrap();
    let mut p = 0usize; let n = rdu32(&b, &mut p) as usize;
    let mut out = String::new();
    out.push_str("/-\n# L5S4.D1Data : the 26 depth-1 nodes of the real certificate (generated by l5s4e_gen from t1.bin + wp0a::child)\n\nNo `sorry`, no `native_decide`, no axiom.  Data only; the checker is `CheckT1`.\n-/\nimport LRSpectrumFull.L5S3.Skeleton\n\nnamespace LRSpectrumFull\nnamespace L5S4\nopen LRSpectrumFull.L5S3\n\n");
    out.push_str("structure D1Raw where\n  h : V5\n  b : Fin 4 → V5\n  s : V5\n  r : Fin 4 → V5\n  x : V5\n  w : ℤ\n\n");
    out.push_str("def d1Data : List D1Raw := [\n");
    let mut stats = vec![];
    for idx in 0..n {
        let mut h = [0 as I; 5]; let mut x = [0 as I; 5];
        for i in 0..5 { h[i] = rdi32(&b, &mut p); } for i in 0..5 { x[i] = rdi32(&b, &mut p); }
        let w = rdu32(&b, &mut p) as i128;
        let nd = child(&root(), &h.to_vec());
        // s with h.s = 1, minimal sup-norm search
        let mut best: Option<V5> = None; 
        'o: for m in 0..=6i128 {
            for a in -m..=m { for bb in -m..=m { for c in -m..=m { for d in -m..=m { for e in -m..=m {
                if a.abs().max(bb.abs()).max(c.abs()).max(d.abs()).max(e.abs()) != m { continue; }
                let s = [a, bb, c, d, e]; if dot(&h, &s) == 1 { best = Some(s); break 'o; }
            } } } } }
        }
        let s = best.expect("no s");
        let ss = dot(&h, &h);
        let m1 = wmin(&x, w);
        stats.push((ss, m1, w, 5 * m1 > w));
        out.push_str(&format!("  {{ h := {}, b := ![{}, {}, {}, {}], s := {}, r := ![{}, {}, {}, {}], x := {}, w := {} }}{}\n",
            v5s(&h), v5s(&nd.b[0]), v5s(&nd.b[1]), v5s(&nd.b[2]), v5s(&nd.b[3]), v5s(&s),
            v5s(&nd.r[0]), v5s(&nd.r[1]), v5s(&nd.r[2]), v5s(&nd.r[3]), v5s(&x), w, if idx + 1 < n { "," } else { "" }));
    }
    out.push_str("]\n\nend L5S4\nend LRSpectrumFull\n");
    std::fs::write(&args[2], out).unwrap();
    for (i, s) in stats.iter().enumerate() { eprintln!("node {} ss={} wmin={} w={} c1>1/5:{}", i, s.0, s.1, s.2, s.3); }
}
