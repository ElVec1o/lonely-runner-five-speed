#!/bin/bash
# make_manifest.sh : (re)generate MANIFEST.tsv, the build order of the five-speed headline theorems.
#
# Root module: LRSpectrumFull.L5S5.FiveSpeedFinal4.  The manifest lists the PROJECT modules (LRSpectrumFull.*) of its import closure
# in DFS post-order (topological: every module appears after all of its project imports).  Mathlib/Batteries/... are not listed.
# Columns: idx module path sha256 bytes lines kind generator in_bundle project_imports
#   in_bundle  no for the regenerable part of the two giant generated families (l5s4o GD3O*, l5qemit LinRQSC*; 8,102 modules, 635 MB): restore with regen_data.sh --full --install.
#              yes for the 184 GD3O modules of GD3O1 (rep 1 main module, not produced by the regeneration chain) and of the eight representatives 265, 304, 927, 1075, 1336, 1343, 1524, 1763 (shipped as files since v1.0.1: the generators do not reproduce them byte for byte)
#   kind      base      = top-level LRSpectrumFull/*.lean and L4Tail/* (older shared modules)
#             generated = emitted by a Rust generator (header says "generated by X", or the family rule below; headerless families are
#                         attributed by file-name pattern and marked with a trailing ? when the attribution was NOT confirmed by a header)
#             hand      = everything else (hand-written Lean)
#   generator  tool name (l5v3 l5s4k_gen l5s4o l5qemit l5reg l5_agg l5_hlines l5s4r_gen l5s4s_gen l5s4e_gen2 l5s4f_gen lean5_wp1 ...) or -
# Usage: bash tools/make_manifest.sh [LEAN_DIR] [OUT]   (reads sources only; writes OUT through a temp file; about 10 s)
HERE=$(cd "$(dirname "$0")/.." && pwd)
LEAN_DIR=${1:-${LEAN_DIR:-$HERE/../lean}}
OUT=${2:-$HERE/MANIFEST.tsv}
ROOT=LRSpectrumFull.L5S5.FiveSpeedFinal4
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
python3 -I "$HERE/tools/closure.py" "$ROOT" "$LEAN_DIR" > "$T/order.txt" || { echo "closure failed; manifest NOT written" >&2; exit 2; }
tr . / < "$T/order.txt" | sed 's/$/.lean/' > "$T/paths.txt"
( cd "$LEAN_DIR" && tr '\n' '\0' < "$T/paths.txt" | xargs -0 shasum -a 256 ) > "$T/sha.txt"
( cd "$LEAN_DIR" && tr '\n' '\0' < "$T/paths.txt" | xargs -0 wc -c ) | grep -v ' total$' > "$T/bytes.txt"
( cd "$LEAN_DIR" && tr '\n' '\0' < "$T/paths.txt" | xargs -0 wc -l ) | grep -v ' total$' > "$T/lines.txt"
[ "$(wc -l < "$T/sha.txt")" = "$(wc -l < "$T/paths.txt")" ] || { echo "sha count mismatch" >&2; exit 2; }
cd "$LEAN_DIR"
awk -v T="$T" '
function famgen(p,   b) {   # attribution by file-name family when the header names no generator; returns "gen" or "gen?" or ""
  b=p; sub(/.*\//,"",b)
  if (p ~ /L5S4\/GD3O[0-9]+(T|Rc[0-9]+(p[0-9]+)?)?\.lean$/ && b !~ /^GD3O(A|D|P|X|XC|call)/) return "l5s4o?"
  if (p ~ /L5S4\/GD3F2N[0-9]+\.lean$/) return "l5v3?"
  if (p ~ /L5S4\/LinRQSG[0-9]+\.lean$/ || p ~ /L5S4\/LinRQSA\.lean$/ || p ~ /L5S4\/LinRAll\.lean$/) return "l5_lines_driver(src_asm)?"
  if (p ~ /L5WP1\/BoxC[0-9]+_[0-9]+\.lean$/) return "lean5_wp1?"
  return ""
}
BEGIN {
  while ((getline l < (T "/sha.txt")) > 0) { split(l,a," "); sha[a[2]]=a[1] }
  while ((getline l < (T "/bytes.txt")) > 0) { split(l,a," "); by[a[2]]=a[1] }
  while ((getline l < (T "/lines.txt")) > 0) { split(l,a," "); li[a[2]]=a[1] }
  print "idx\tmodule\tpath\tsha256\tbytes\tlines\tkind\tgenerator\tin_bundle\tproject_imports"
  i=0
  while ((getline p < (T "/paths.txt")) > 0) {
    i++; m=p; sub(/\.lean$/,"",m); gsub(/\//,".",m)
    g="-"; n=0; imps=""
    while ((getline line < p) > 0) {
      n++
      if (n<=12 && g=="-" && match(tolower(line), /(generated|emitted)[a-z ]{0,8} by `?[a-z0-9_]+/)) { s=substr(tolower(line),RSTART,RLENGTH); sub(/.* by `?/,"",s); if (s!="the" && s!="private") g=s }
      if (line ~ /^import LRSpectrumFull\./) { x=line; sub(/^import /,"",x); sub(/\r$/,"",x); imps = imps (imps==""?"":",") x }
      if (n>12 && line !~ /^import /) { if (line !~ /^[ \t]*$/ && line !~ /^(\/-|-\/|--)/) { } }
    }
    close(p)
    kind="hand"
    if (g!="-") kind="generated"
    else { f=famgen(p); if (f!="") { kind="generated"; g=f } }
    if (p ~ /^LRSpectrumFull\/[^\/]*\.lean$/ || p ~ /^LRSpectrumFull\/L4Tail\//) kind="base"
    inb="yes"; if (g ~ /^(l5s4o\?|l5qemit)$/) inb="no"
    if (p ~ /L5S4\/GD3O(265|304|927|1075|1336|1343|1524|1763)(T|Rc[0-9]+(p[0-9]+)?)?\.lean$/ || p ~ /L5S4\/GD3O1\.lean$/) inb="yes"
    printf "%d\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n", i, m, p, sha[p], by[p], li[p], kind, g, inb, imps
  }
}' > "$T/m.tsv"
# self-check: topological order
BAD=$(awk -F'\t' 'NR==FNR{if(FNR>1)idx[$2]=$1; next} FNR>1{n=split($10,a,","); for(j=1;j<=n;j++) if(a[j]!="" && !(a[j] in idx && idx[a[j]]<$1)) print $2" imports "a[j]}' "$T/m.tsv" "$T/m.tsv")
[ -z "$BAD" ] || { echo "ORDER VIOLATION:" >&2; echo "$BAD" | head >&2; exit 3; }
mv "$T/m.tsv" "$OUT"
echo "wrote $OUT: $(($(wc -l < "$OUT")-1)) modules"
